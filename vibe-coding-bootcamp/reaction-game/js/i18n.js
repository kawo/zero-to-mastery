  const DICTS = { en, fr };
  let lang = 'en';

  function detect() {
    // The browser's first preferred language decides; anything but French → English.
    const first = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    return String(first).toLowerCase().startsWith('fr') ? 'fr' : 'en';
  }

  function setLang(next) {
    lang = DICTS[next] ? next : 'en';
    document.documentElement.lang = lang;
    return lang;
  }

  const getLang = () => lang;
  const locale = () => LANGS[lang].locale;

  function lookup(key) {
    if (Object.prototype.hasOwnProperty.call(DICTS[lang], key)) return DICTS[lang][key];
    if (Object.prototype.hasOwnProperty.call(en, key)) return en[key];
    return null;
  }

  function fill(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (m, name) => (
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m));
  }

  /** Translate a UI key. */
  function t(key, params) {
    let text = null;
    if (params && typeof params.n === 'number') {
      const singular = lang === 'fr' ? params.n <= 1 : params.n === 1;
      text = lookup(`${key}.${singular ? 'one' : 'other'}`);
    }
    if (text === null) text = lookup(key);
    if (text === null) return key;
    return fill(text, params);
  }

  /** Translate game data: French from here, otherwise the English from the data file. */
  function td(key, english, params) {
    const text = lang !== 'en' && Object.prototype.hasOwnProperty.call(DICTS[lang], key) ? DICTS[lang][key] : english;
    return fill(String(text == null ? '' : text), params);
  }

  /** Translate static markup under `root`. */
  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
      for (const pair of el.dataset.i18nAttr.split(';')) {
        const [attr, key] = pair.split(':').map((s) => s.trim());
        if (attr && key) el.setAttribute(attr, t(key));
      }
    });
  }

  window.ReflexLabI18n = Object.freeze({ LANGS, t, td, apply, setLang, getLang, locale, detect });
